/** يضمن أن كل كرت له تصنيف؛ الكرت المضاف يدوياً يقرأ كمحايد حتى يصنّف صراحة. */
export function getCardAlignment(card: Pick<Card, 'id' | 'alignment'>): CardAlignment {
  return card.alignment ?? CARD_ALIGNMENT_BY_ID[card.id] ?? 'neutral';
}

export function attachCardAlignments(cards: Card[]): Card[] {
  return cards.map((card) => ({ ...card, alignment: getCardAlignment(card) }));
}
