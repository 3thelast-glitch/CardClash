/**
 * Get full structured detail for an ability
 */
export function getAbilityDetail(abilityType: AbilityType): AbilityDetail | undefined {
  return ABILITY_DETAILS[abilityType];
}

/**
 * Build a single-line summary for toast/modal display
 * e.g. "⚡ فوري · +2 هجوم و +2 دفاع · ⏱ دائم"
 */
export function getAbilitySummaryLine(abilityType: AbilityType): string {
  const d = ABILITY_DETAILS[abilityType];
  if (!d) return '';
  const cat = CATEGORY_CONFIG[d.category];
  return `${cat.emoji} ${d.triggerAr} · ${d.effectAr}`;
}
