/**
 * ability-details.ts
 * ─────────────────
 * Structured ability data for the UI — every ability has:
 *   - trigger: when it activates
 *   - effect:  what stat / game state it changes
 *   - duration: how long it lasts
 *   - category: buff / debuff / utility / special
 *   - targetSide: who it affects
 *   - condition/cooldown: any limits
 */
